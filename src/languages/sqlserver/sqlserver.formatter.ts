// https://learn.microsoft.com/en-us/sql/t-sql/language-reference
export const sqlserver: DialectOptions = {
    name: "sqlserver",
    tokenizerOptions: {
        reservedSelect,
        reservedClauses: [
            ...reservedClauses,
            ...standardOnelineClauses,
            ...tabularOnelineClauses,
        ],
        reservedSetOperations,
        reservedJoins,
        reservedKeywordPhrases,
        reservedDataTypePhrases,
        reservedKeywords: keywords,
        reservedDataTypes: dataTypes,
        reservedFunctionNames: functions,
        // SQL Server string types:
        // - ''-qq-bs: standard single-quoted strings with '' and \ escaping
        // - N''-bs: Unicode string (N prefix) with backslash escaping
        // - X'': binary string (X prefix)
        stringTypes: [
            "''-qq-bs",
            { quote: "''-bs", prefixes: ["N"], requirePrefix: false },
            { quote: "''-raw", prefixes: ["X"], requirePrefix: true },
        ],
        // SQL Server identifier types:
        // - []: bracket-quoted identifiers (T-SQL style)
        // - "": double-quoted identifiers (SQL standard, supported when QUOTED_IDENTIFIER ON)
        identTypes: ["[]", '""-qq'],
        // SQL Server variables:
        // - @name: local variables
        // - @@name: global/system variables (e.g., @@ROWCOUNT, @@IDENTITY)
        variableTypes: [
            { regex: "@@?[A-Za-z0-9_.$]+" },
        ],
        paramTypes: { positional: true },
        lineCommentTypes: ["--"],
        operators: [
            "+", // string concatenation and addition
            "%", // modulo
            ":=",
            "&",
            "|",
            "^",
            "~",
            "<<",
            ">>",
            "&&",
            "||",
            "!",
            "*.*",
        ],
    },
    formatOptions: {
        onelineClauses: [...standardOnelineClauses, ...tabularOnelineClauses],
        tabularOnelineClauses,
    },
}
